// The profile-media crop stage (see AGENTS.md -> verification conventions).
//
// Setting an avatar, a banner or the member-list banner is framed before the
// bytes are stored, because every render site crops with `cover` on its own (and
// a circle for an avatar). Three halves:
//
//   [1] the transform, driven straight out of public/js/crop.js: the window is
//       cover-fitted, a drag can never pull the picture off the window, zoom is
//       bounded and anchored on the point under the cursor, and the RECTANGLE
//       handed to the server never leaves the picture's own pixels. This is the
//       part that is wrong invisibly, so it is measured, not eyeballed.
//   [2] the encoder, on real generated bytes: a real animated GIF crops to a
//       real animated GIF (the point of the whole feature — a canvas would have
//       returned one frame), a still crops to WebP at the requested size, the
//       long side is capped and never enlarged, and an out-of-bounds rectangle
//       is clamped rather than refused. Skips without ffmpeg/ffprobe.
//   [3] the wiring, as source: the two routes, the client hookups, the layer,
//       the shell cache. A stage nothing calls is not a feature.
//
// Re-run after touching public/js/crop.js, image-crop.js, the profile routes in
// server.js, or the avatar/banner hookups in settings.js / admin.js.
//
// Usage: node scripts/test-image-crop.js
'use strict';

const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const ROOT = path.join(__dirname, '..');

let passed = 0;
const failures = [];
function check(name, cond, detail) {
  if (cond) { passed++; console.log('  ok   ' + name); }
  else { failures.push(name + (detail ? ' — ' + detail : '')); console.log('  FAIL ' + name + (detail ? ' — ' + detail : '')); }
}
function skip(msg) { console.log('[test] SKIP: ' + msg); process.exit(0); }

const cropJs = fs.readFileSync(path.join(ROOT, 'public/js/crop.js'), 'utf8');
const server = fs.readFileSync(path.join(ROOT, 'server.js'), 'utf8');
const index = fs.readFileSync(path.join(ROOT, 'public/index.html'), 'utf8');
const settings = fs.readFileSync(path.join(ROOT, 'public/js/settings.js'), 'utf8');
const pickers = fs.readFileSync(path.join(ROOT, 'public/js/pickers.js'), 'utf8');
const admin = fs.readFileSync(path.join(ROOT, 'public/js/admin.js'), 'utf8');
const finalJs = fs.readFileSync(path.join(ROOT, 'public/js/final.js'), 'utf8');
const css = fs.readFileSync(path.join(ROOT, 'public/styles.css'), 'utf8');
const sw = fs.readFileSync(path.join(ROOT, 'public/service-worker.js'), 'utf8');
const mc = fs.readFileSync(path.join(ROOT, 'media-compress.js'), 'utf8');

// ---------- [1] the transform ----------
const START = '// ---------- the crop transform (pure: no DOM, no globals) ----------';
const END = '// ---------- end of the pure transform ----------';
const a = cropJs.indexOf(START), b = cropJs.indexOf(END);
if (a < 0 || b < 0 || b < a) { console.log('FAIL the pure-transform block is not marked'); process.exit(1); }
const src = cropJs.slice(a + START.length, b)
  // The prose between the markers mentions the server, so strip comments before
  // evaluating: the block must be arithmetic only.
  .replace(/^\s*\/\/.*$/gm, '');
let T = null;
try {
  T = new Function(src + '\nreturn { CROP_MAX_ZOOM, cropCoverScale, cropViewInit, cropViewClamp, cropViewZoomAt, cropViewRect, cropBgStyle };')();
} catch (e) {
  console.log('FAIL the pure-transform block does not evaluate: ' + e.message);
  process.exit(1);
}

console.log('-- [1] the window transform: cover, clamped, anchored --');
{
  // 400x400 into a 200x200 window: cover is 0.5, the picture is exactly the
  // window, and the rectangle is the whole picture.
  const v = T.cropViewInit(400, 400, 200, 200);
  check('a square covers a square window at exactly 1:1 of the window',
    v.scale === 0.5 && v.ox === 0 && v.oy === 0, JSON.stringify(v));
  const r = T.cropViewRect(v);
  check('and the whole picture is the frame', r.x === 0 && r.y === 0 && r.w === 400 && r.h === 400, JSON.stringify(r));

  // 800x200 into a 600x200 window (3:1 banner shape): cover = 1, the picture is
  // wider than the window, so it is centred and the frame is the window's own
  // 600x200 slice out of the middle.
  const w = T.cropViewInit(800, 200, 600, 200);
  check('a wide banner is centred in a 3:1 window', w.scale === 1 && w.ox === -100 && w.oy === 0, JSON.stringify(w));
  const rw = T.cropViewRect(w);
  check('and its frame is the middle 600x200 of the source',
    rw.x === 100 && rw.y === 0 && rw.w === 600 && rw.h === 200, JSON.stringify(rw));

  // A tall picture in a wide window (a portrait photo as a sidebar banner):
  // cover is set by the WIDTH (1.5), so the window sees a 400x67 band of it.
  const t = T.cropViewInit(400, 1200, 600, 100);
  check('a portrait covers a 6:1 window by width', t.scale === 1.5 && t.ox === 0 && Math.abs(t.oy - (-850)) < 1e-6, JSON.stringify(t));
  const rt = T.cropViewRect(t);
  check('and its frame is a 400x67 band, inside the picture',
    rt.x === 0 && rt.w === 400 && rt.h === 67 && rt.y >= 0 && rt.y + rt.h <= 1200, JSON.stringify(rt));

  // Dragging: a huge drag stops at the picture's own edge, never past it.
  const drag = T.cropViewClamp({ ...T.cropViewInit(800, 200, 600, 200), ox: 9999, oy: -9999 });
  check('a drag past the edge stops at the edge', drag.ox === 0 && drag.oy === 0, JSON.stringify(drag));
  const drag2 = T.cropViewClamp({ ...T.cropViewInit(800, 200, 600, 200), ox: -9999, oy: 9999 });
  check('and the other way stops at the far edge', drag2.ox === -200 && drag2.oy === 0, JSON.stringify(drag2));

  // Zoom: refused below cover (that would show bare stage) and capped above.
  const out = T.cropViewClamp({ ...T.cropViewInit(800, 200, 600, 200), scale: 0.01 });
  check('zooming out below cover is refused', out.scale === 1, String(out.scale));
  const inMax = T.cropViewClamp({ ...T.cropViewInit(800, 200, 600, 200), scale: 1000 });
  check('zooming in is capped at ' + T.CROP_MAX_ZOOM + 'x cover', inMax.scale === T.CROP_MAX_ZOOM, String(inMax.scale));

  // The anchor property: the source pixel under (px,py) is the SAME pixel after
  // a zoom, which is what makes a wheel/pinch feel attached to the picture.
  const base = T.cropViewInit(1600, 900, 600, 200);
  const anchor = { x: 411, y: 77 };
  const before = { x: (anchor.x - base.ox) / base.scale, y: (anchor.y - base.oy) / base.scale };
  const zoomed = T.cropViewZoomAt(base, base.scale * 2.4, anchor.x, anchor.y);
  const after = { x: (anchor.x - zoomed.ox) / zoomed.scale, y: (anchor.y - zoomed.oy) / zoomed.scale };
  check('a zoom keeps the source pixel under the pointer',
    Math.abs(before.x - after.x) < 1e-6 && Math.abs(before.y - after.y) < 1e-6,
    JSON.stringify({ before, after }));

  // The property that matters most: the rectangle is always INSIDE the picture.
  let worst = null;
  for (const nat of [[800, 200], [400, 1200], [1920, 1080], [64, 64], [3000, 3000]]) {
    for (const win of [[600, 200], [200, 200], [520, 87], [120, 20]]) {
      let v2 = T.cropViewInit(nat[0], nat[1], win[0], win[1]);
      for (const step of [[37, -11], [-500, 0], [0, 900], [12, 12]]) {
        v2 = T.cropViewClamp({ ...v2, ox: v2.ox + step[0], oy: v2.oy + step[1] });
        for (const s of [0.2, 1, 3.7]) {
          v2 = T.cropViewZoomAt(v2, v2.min * s, (win[0] / 2) + 13, (win[1] / 2) - 7);
          const rr = T.cropViewRect(v2);
          // One pixel of rounding slack: the rect is rounded OUT of a fractional
          // offset, and the server clamps the last pixel anyway.
          const ok = rr.x >= -1 && rr.y >= -1 && rr.w >= 1 && rr.h >= 1
            && rr.x + rr.w <= nat[0] + 1 && rr.y + rr.h <= nat[1] + 1;
          if (!ok && !worst) worst = { nat, win, rr };
        }
      }
    }
  }
  check('no drag/zoom combination ever frames pixels outside the picture', !worst, worst ? JSON.stringify(worst) : '');

  // The preview is the SAME crop: scaled by k, it must resolve to the identical
  // source rectangle — otherwise the little box under the stage lies.
  const pv = T.cropViewInit(1600, 900, 600, 200);
  const pvz = T.cropViewZoomAt(pv, pv.min * 1.9, 250, 60);
  const k = 228 / pvz.winW;
  const bg = T.cropBgStyle(pvz, k);
  const size = bg.size.match(/([\d.]+)px ([\d.]+)px/);
  const pos = bg.pos.match(/(-?[\d.]+)px (-?[\d.]+)px/);
  const prevRect = {
    x: -Number(pos[1]) / (Number(size[1]) / pvz.natW),
    y: -Number(pos[2]) / (Number(size[2]) / pvz.natH),
    w: (pvz.winW * k) / (Number(size[1]) / pvz.natW),
    h: (pvz.winH * k) / (Number(size[2]) / pvz.natH),
  };
  const stageRect = T.cropViewRect(pvz);
  check('the preview box shows the same source rectangle as the window',
    Math.abs(prevRect.x - stageRect.x) < 1 && Math.abs(prevRect.w - stageRect.w) < 1
    && Math.abs(prevRect.y - stageRect.y) < 1 && Math.abs(prevRect.h - stageRect.h) < 1,
    JSON.stringify({ prevRect, stageRect }));
}

// ---------- [2] the encoder, on real bytes ----------
const ffOk = (() => { const r = spawnSync('ffmpeg', ['-version'], { stdio: 'ignore' }); return !!(r && r.status === 0); })();
const fpOk = (() => { const r = spawnSync('ffprobe', ['-version'], { stdio: 'ignore' }); return !!(r && r.status === 0); })();

async function encoder() {
  if (!ffOk || !fpOk) { console.log('\n-- [2] the encoder: SKIPPED (no ffmpeg/ffprobe on PATH) --'); return; }
  const ic = require(path.join(ROOT, 'image-crop.js'));
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'cf-crop-'));
  const f = (n) => path.join(tmp, n);
  const ff = (args) => { const r = spawnSync('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-y', ...args], { stdio: 'ignore' }); return !!(r && r.status === 0); };
  const probe = (p) => {
    const r = spawnSync('ffprobe', ['-v', 'error', '-select_streams', 'v:0', '-count_frames',
      '-show_entries', 'stream=width,height,codec_name,nb_read_frames', '-of', 'default=nw=1', p], { encoding: 'utf8' });
    const out = {};
    for (const line of String(r.stdout || '').split('\n')) {
      const [k, v] = line.split('=');
      if (k && v) out[k.trim()] = v.trim();
    }
    return out;
  };
  console.log('\n-- [2] the encoder: a GIF crops to a GIF that still moves --');
  try {
    // A real 8-frame animation and a real still, both generated here: no
    // fixtures to go stale.
    const gif = f('anim.gif'), png = f('still.png'), webp = f('anim.webp');
    check('generated a real 8-frame GIF', ff(['-f', 'lavfi', '-i', 'testsrc=size=200x120:rate=8', '-frames:v', '8', gif]));
    check('generated a real still PNG', ff(['-f', 'lavfi', '-i', 'testsrc=size=400x300', '-frames:v', '1', png]));
    const gifBuf = fs.readFileSync(gif), pngBuf = fs.readFileSync(png);
    check('the generator output probes as 8 frames', probe(gif).nb_read_frames === '8', JSON.stringify(probe(gif)));

    // Detection: the same picture, animated and not.
    check('an 8-frame GIF reads as animated', ic.isAnimatedImage(gifBuf, 'image/gif') === true);
    check('a still PNG does not', ic.isAnimatedImage(pngBuf, 'image/png') === false);
    if (ff(['-f', 'lavfi', '-i', 'testsrc=size=200x120:rate=8', '-frames:v', '1', f('one.gif')])) {
      check('a one-frame GIF does not', ic.isAnimatedImage(fs.readFileSync(f('one.gif')), 'image/gif') === false);
    }
    if (ff(['-f', 'lavfi', '-i', 'testsrc=size=120x80:rate=6', '-frames:v', '6', '-c:v', 'libwebp_anim', '-loop', '0', webp])) {
      check('an animated WebP reads as animated', ic.isAnimatedImage(fs.readFileSync(webp), 'image/webp') === true);
    } else { console.log('  NOTE this ffmpeg has no libwebp_anim — skipping the WebP animation check'); }
    check('truncated bytes do not', ic.isAnimatedImage(gifBuf.slice(0, 12), 'image/gif') === false);

    // The crop itself. The rect is the one the stage would hand over for a
    // 200x120 window... here it is a plain 120x60 corner.
    const rect = { x: 40, y: 30, w: 120, h: 60 };
    const out = await ic.cropImage({ buf: gifBuf, mime: 'image/gif', rect, cap: 1080 });
    check('the GIF crop produced bytes', !!(out && out.buffer && out.buffer.length), out ? String(out.buffer.length) : 'null');
    check('and they are a GIF', out && out.mime === 'image/gif' && out.ext === '.gif', out && out.mime);
    check('at exactly the requested frame', out && out.w === 120 && out.h === 60, out && `${out.w}x${out.h}`);
    if (out) {
      fs.writeFileSync(f('out.gif'), out.buffer);
      const p = probe(f('out.gif'));
      check('with the ANIMATION intact (8 frames, not 1)',
        p.nb_read_frames === '8' && p.width === '120' && p.height === '60', JSON.stringify(p));
    }

    const still = await ic.cropImage({ buf: pngBuf, mime: 'image/png', rect: { x: 100, y: 50, w: 200, h: 200 }, cap: 512 });
    check('a still crops to WebP', !!(still && still.mime === 'image/webp'), still && still.mime);
    check('at the requested size', still && still.w === 200 && still.h === 200, still && `${still.w}x${still.h}`);
    if (still) {
      fs.writeFileSync(f('out.webp'), still.buffer);
      const p = probe(f('out.webp'));
      check('and the stored bytes really are that size', p.width === '200' && p.height === '200' && p.codec_name === 'webp', JSON.stringify(p));
    }

    // A big frame is capped on its long side; a small one is NEVER enlarged.
    const big = await ic.cropImage({ buf: pngBuf, mime: 'image/png', rect: { x: 0, y: 0, w: 400, h: 300 }, cap: 200 });
    check('a frame past the cap is capped, keeping its shape',
      big && big.w === 200 && big.h === 150, big && `${big.w}x${big.h}`);
    const small = await ic.cropImage({ buf: pngBuf, mime: 'image/png', rect: { x: 10, y: 10, w: 40, h: 40 }, cap: 512 });
    check('a frame under the cap is not enlarged', small && small.w === 40 && small.h === 40, small && `${small.w}x${small.h}`);

    // A rectangle that runs off the picture is clamped into it rather than
    // refused: the last 100x100 of a 400x300 still, at its bottom-right corner.
    const oob = await ic.cropImage({ buf: pngBuf, mime: 'image/png', rect: { x: 380, y: 290, w: 100, h: 100 }, cap: 512 });
    check('a rectangle running off the picture is clamped to its corner',
      oob && oob.w === 100 && oob.h === 100, oob && `${oob.w}x${oob.h}`);
    if (oob) {
      fs.writeFileSync(f('oob.webp'), oob.buffer);
      const p = probe(f('oob.webp'));
      check('and the stored bytes are the clamped frame', p.width === '100' && p.height === '100', JSON.stringify(p));
    }
    const swallow = await ic.cropImage({ buf: pngBuf, mime: 'image/png', rect: { x: 380, y: 290, w: 900, h: 900 }, cap: 512 });
    check('a rectangle bigger than the picture becomes the whole picture',
      swallow && swallow.w === 400 && swallow.h === 300, swallow && `${swallow.w}x${swallow.h}`);
    check('a rectangle of nonsense is refused', (await ic.cropImage({ buf: pngBuf, mime: 'image/png', rect: { x: 'a', y: 0, w: 10, h: 10 }, cap: 512 })) === null);
    check('bytes that are not an image are refused', (await ic.cropImage({ buf: Buffer.from('definitely not a picture'), mime: 'image/png', rect: { x: 0, y: 0, w: 10, h: 10 }, cap: 512 })) === null);

    // The cap per surface, so the three fields cannot drift apart silently.
    check('avatar caps at 512, banner at 1200, sidebar at 1080',
      ic.CROP_KINDS.avatar.cap === 512 && ic.CROP_KINDS.banner.cap === 1200 && ic.CROP_KINDS.sidebar.cap === 1080,
      JSON.stringify(ic.CROP_KINDS));
    check('and each names the column it writes',
      ic.CROP_KINDS.avatar.col === 'avatar_url' && ic.CROP_KINDS.banner.col === 'banner_url' && ic.CROP_KINDS.sidebar.col === 'sidebar_banner_url');
  } finally {
    try { fs.rmSync(tmp, { recursive: true, force: true }); } catch {}
  }
}

// ---------- [3] the wiring ----------
function wiring() {
  console.log('\n-- [3] the wiring: routes, hookups, layer, cache --');
  check('the member route exists', /app\.post\('\/api\/me\/:kind\/crop', authRequired, upCrop\.single\('file'\)/.test(server));
  check('the admin route exists', /app\.post\('\/api\/admin\/users\/:id\/:kind\/crop'/.test(server));
  check('the crop source is buffered in memory, never stored as an upload',
    /uploader\('avatars', IMG_MIMES, MAX_IMG_BYTES, false, \{ memory: true \}\)/.test(server));
  check('a remote source goes through the SSRF-guarded fetch', /unfurl'\)\.fetchImage\(url\)/.test(server));
  check('one crop per account at a time', /CROP_BUSY\.has\(req\.user\.id\)/.test(server));
  check('the bytes are stored like an upload (scan + compress kicks)',
    /async function storeGeneratedImage/.test(server) && /queueFileScan\(key\)/.test(server) && /kickProfileMedia\(key\)/.test(server));

  check('index.html loads crop.js before settings.js (which calls into it)',
    index.indexOf('/js/crop.js') > 0 && index.indexOf('/js/crop.js') < index.indexOf('/js/settings.js'));
  check('and carries the layer it drives',
    /id="crop-backdrop"/.test(index) && /id="crop-stage"/.test(index) && /id="crop-preview"/.test(index) && /id="crop-save"/.test(index));
  check('the stage sits ABOVE the dialog layer, under the lightbox',
    /#crop-backdrop\{[^}]*z-index:190/.test(css) && /#lightbox\{[^}]*z-index:200/.test(css));

  check('all three upload buttons go through the crop stage',
    (settings.match(/cropProfileMedia\('(avatar|banner|sidebar)', \{ file: f \}\)/g) || []).length === 3);
  check('the Use GIF picker does too, by URL', /cropProfileMedia\(kind, \{ url \}\)/.test(settings));
  check('the GIF picker no longer sets a picture on the spot', !/if \(url\) await applyProfileUrl\(kind, url\)/.test(settings));
  check('a history dot re-frames what it re-uses', /b\.onclick = \(\) => cropProfileMedia\(kind, \{ url: it\.url \}\)/.test(pickers));
  check('and a /uploads history entry is read back into bytes for the route (which only fetches https)',
    /if \(!file && \/\^\\\/uploads\\\/\/\.test\(url\)\)/.test(settings));
  check('the admin uploads go through it as well', /pickFile\(\(f\) => openCropStage\(/.test(admin));
  check('and hit the admin route', /\/api\/admin\/users\/\$\{u\.id\}\/\$\{kind === 'sidebar-banner' \? 'sidebar' : kind\}\/crop/.test(admin));
  check('Escape peels the stage like every other layer', /\(\) => closeCropStage\(\)/.test(finalJs));
  // The shell cache must carry the module — and a LITERAL version here goes
  // stale on the next unrelated bump (which is how this check sat red), so it
  // asks the question that actually matters: at or past the release that added
  // crop.js, and holding it.
  const cacheV = Number(((sw.match(/CACHE = 'campfire-v(\d+)'/) || [])[1]) || 0);
  check('the shell cache carries the crop module (at or past the version that added it, v585)',
    cacheV >= 585 && /'\/js\/crop\.js'/.test(sw));
  check('the compressor lends its runner and its encode slot',
    /runFfmpeg, checkFfmpeg, withCompressLock,/.test(mc) && /function runFfmpeg\(args, opts\)/.test(mc));
  check('the crop takes that slot', /withCompressLock\(\(\) => runFfmpeg\(args, \{ timeoutMs: CROP_TIMEOUT_MS \}\)\)/.test(
    fs.readFileSync(path.join(ROOT, 'image-crop.js'), 'utf8')));
}

(async () => {
  try {
    await encoder();
    wiring();
  } catch (e) {
    failures.push('threw: ' + ((e && e.stack) || e));
    console.log('  FAIL threw: ' + ((e && e.message) || e));
  }
  console.log(`\n${passed} passed, ${failures.length} failed`);
  if (failures.length) { for (const f of failures) console.log('  - ' + f); process.exit(1); }
})();
