// Offline check of what the compressor will ATTEMPT — no server, no database:
//   - the size floor (there is none by default: any size is attempted),
//   - the type routing (every image / video / audio family, plus what must
//     never be handed to ffmpeg),
//   - how a deferred 'still' plan resolves against real bytes (alpha -> PNG,
//     opaque -> JPEG, an animation left exactly as it is),
//   - the HEIC/HEIF path end to end when libheif is installed (heif-convert ->
//     JPEG -> the ordinary still pipeline), including the rule that a
//     normalized conversion publishes even when it is bigger,
//   - the Apple rule: Opus/Vorbis audio and the video containers Safari cannot
//     demux are converted to AAC/MP4 and MP4 at ANY size (a voice note recorded
//     on Chrome used to stay WebM and play as silence on an iPhone), while
//     MP3/AAC/WAV/FLAC and MP4/MOV keep the ordinary 8% rule — proved on real
//     generated bytes, including that the moov atom lands before the audio data.
//
// The plumbing around it (slot, serving gate, ledger, bucket scan) is covered
// end-to-end by scripts/test-upload-pipeline.js; this file is the coverage
// contract itself, so it runs anywhere and only needs ffmpeg + ffprobe (plus
// heif-convert for the HEIC half, which the app image installs).
//
// Re-run after touching media-compress.js: planFor, resolvePlan, MIN_BYTES,
// shouldPublish/encodeCandidate.
// Usage: node scripts/test-compress-types.js
'use strict';

const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const media = require('../media-compress');

// A real 16x16 HEIC, 455 bytes, encoded with libheif's own heif-enc (red frame,
// quality 1) and committed here as base64: the container has no HEIF *encoder*
// either, so a HEIC fixture cannot be generated on the box at test time — and
// this is the only way to prove the decode half without a network fetch.
const TINY_HEIC_B64 = 'AAAAHGZ0eXBoZWljAAAAAG1pZjFoZWljbWlhZgAAAX1tZXRhAAAAAAAAACFoZGxyAAAAAAAAAABwaWN0AAAAAAAAAAAAAAAAAAAAAA5waXRtAAAAAAABAAAAImlsb2MAAAAAREAAAQABAAAAAAGhAAEAAAAAAAAAJgAAACNpaW5mAAAAAAABAAAAFWluZmUCAAAAAAEAAGh2YzEAAAAA/WlwcnAAAADdaXBjbwAAAHZodmNDAQNwAAAAAAAAAAAAHvAA/P34+AAADwMgAAEAGEABDAH//wNwAAADAJAAAAMAAAMAHroCQCEAAQAqQgEBA3AAAAMAkAAAAwAAAwAeoCCBBZbqrprm4CGgwIAAAAMAgAAAAwCEIgABAAZEAcFzwYkAAAATY29scm5jbHgAAQANAAaAAAAAFGlzcGUAAAAAAAAAQAAAAEAAAAAoY2xhcAAAABAAAAABAAAAEAAAAAH////QAAAAAv///9AAAAACAAAAEHBpeGkAAAAAAwgICAAAABhpcG1hAAAAAAAAAAEAAQWBAgMFhAAAAC5tZGF0AAAAIigBrwUSE0zg+rpSO5/jWHx8Bt5ez5Ws7xb8oJVaEJHxW0A=';

let passed = 0;
const failures = [];
function check(name, cond, detail) {
  if (cond) { passed++; console.log('  ok   ' + name); }
  else { failures.push(name + (detail ? ' — ' + detail : '')); console.log('  FAIL ' + name + (detail ? ' — ' + detail : '')); }
}

const gen = (args, out) => {
  const r = spawnSync('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-y', ...args, out], { stdio: 'ignore' });
  return !!(r && r.status === 0 && fs.existsSync(out) && fs.statSync(out).size);
};

async function main() {
  const ff = spawnSync('ffmpeg', ['-version'], { stdio: 'ignore' });
  if (!ff || ff.status !== 0) return skip('ffmpeg not found on PATH');
  const fp = spawnSync('ffprobe', ['-version'], { stdio: 'ignore' });
  if (!fp || fp.status !== 0) return skip('ffprobe not found on PATH');

  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'cf-types-'));
  const f = (n) => path.join(tmp, n);
  try {
    const enc = media.probeEncoders();

    console.log('-- size: there is no floor, so every size is attempted --');
    check('MIN_BYTES is empty by default',
      media.MIN_KB === 0 && ['image', 'gif', 'video', 'audio'].every((g) => media.MIN_BYTES[g] === 0),
      JSON.stringify(media.MIN_BYTES));
    check('a 174-byte png is a candidate', media.isCandidate('image/png', 'files/a.png', 174) === true);
    check('a 300-byte mp4 is a candidate', media.isCandidate('video/mp4', 'files/a.mp4', 300) === true);
    check('a 2 KB wav is a candidate', media.isCandidate('audio/wav', 'files/a.wav', 2048) === true);
    check('a tiny gif is a candidate', media.isCandidate('image/gif', 'files/a.gif', 512) === true);
    check('a zip is NOT a candidate', media.isCandidate('application/zip', 'files/a.zip', 9 * 1024 * 1024) === false);
    check('a pdf is NOT a candidate', media.isCandidate('application/pdf', 'files/a.pdf', 9 * 1024 * 1024) === false);
    check('source code is NOT a candidate', media.isCandidate('text/plain', 'files/a.ts', 4096) === false);
    check('an svg is NOT a candidate', media.isCandidate('image/svg+xml', 'files/a.svg', 4096) === false);
    check('an unidentifiable binary is NOT a candidate', media.isCandidate('application/octet-stream', 'files/a.bin', 9 * 1024 * 1024) === false);

    console.log('\n-- routing: every media family the box can decode --');
    check('jpeg -> jpeg', (media.planFor('image/jpeg', 'files/a.jpg') || {}).pipeline === 'jpeg');
    check('png goes lossy to WebP when libwebp is there (owner decision)',
      (media.planFor('image/png', 'files/a.png') || {}).prefer === (enc.webp ? 'webp' : 'png'),
      JSON.stringify(media.planFor('image/png', 'files/a.png')));
    check('gif keeps its animation-aware pipeline', (media.planFor('image/gif', 'files/a.gif') || {}).pipeline === 'gif');
    check('webp is routed (own encoder, or alpha-driven)',
      !enc.webp ? (media.planFor('image/webp', 'files/a.webp') || {}).pipeline === 'still' : (media.planFor('image/webp', 'files/a.webp') || {}).prefer === 'webp');

    // Stills with no pipeline of their own are deferred to the bytes. Both the
    // client's MIME and the name alone (what the bucket scan has) must route.
    for (const [mime, key] of [
      ['image/bmp', 'files/a.bmp'], ['image/tiff', 'files/a.tif'], ['image/avif', 'files/a.avif'],
      ['image/jxl', 'files/a.jxl'], ['image/vnd.microsoft.icon', 'files/a.ico'],
      ['application/octet-stream', 'files/a.bmp'],
    ]) {
      const plan = media.planFor(mime, key);
      check(mime + ' ' + path.extname(key) + ' -> deferred still', !!plan && plan.pipeline === 'still', JSON.stringify(plan));
    }

    console.log('\n-- HEIC/HEIF: the one family ffmpeg cannot open at all --');
    // The container's ffmpeg has no HEIF demuxer (Alpine builds it without
    // libheif), so a HEIC is decoded by heif-convert and encoded as a JPEG. Its
    // plan is marked `normalize`: the conversion is published even when it is
    // NOT smaller, because the original cannot be displayed by any Windows
    // browser or viewer — which is the whole point of the pipeline.
    const heif = media.checkHeifConvert();
    const heifPlan = media.planFor('image/heic', 'files/a.heic');
    if (!heif) {
      check('with no heif-convert installed a HEIC is left alone (null plan, nothing lost)',
        heifPlan === null && media.planFor('application/octet-stream', 'files/a.heic') === null, JSON.stringify(heifPlan));
      console.log('  note  heif-convert is not on PATH — the decode half is skipped (the app image installs libheif-tools)');
    } else {
      for (const [mime, key] of [
        ['image/heic', 'files/a.heic'], ['image/heif', 'files/a.heif'],
        ['application/octet-stream', 'files/a.heic'], ['application/octet-stream', 'files/a.HEIC'],
        ['image/heic-sequence', 'files/x.bin'],
      ]) {
        const p = media.planFor(mime, key);
        check(mime + ' ' + path.extname(key) + ' -> heif normalize', !!p && p.pipeline === 'heif' && p.outExt === '.jpg' && p.normalize === true, JSON.stringify(p));
      }
      check('the heif plan is never sent to buildArgs (ffmpeg cannot read the input)',
        (() => { try { media.buildArgs('heif', 'in', 'out'); return false; } catch { return true; } })());
      check('a HEIC is a candidate for the pre-publication slot',
        media.isCandidate('image/heic', 'files/a.heic', 471520) === true && media.isCandidate('application/octet-stream', 'files/a.heic', 471520) === true);
      // A normalized conversion publishes whatever came out, at any size; every
      // other pipeline keeps the 8% rule (and a zero-byte output is never
      // published, normalize or not — that is a failed encode, not a file).
      check('normalize publishes even when the JPEG is bigger',
        media.shouldPublish({ pipeline: 'heif', normalize: true }, 1000, 5000) === true);
      check('an ordinary still keeps the 8% rule',
        media.shouldPublish({ pipeline: 'jpeg' }, 1000, 950) === false && media.shouldPublish({ pipeline: 'jpeg' }, 1000, 900) === true);
      check('an empty candidate is never published', media.shouldPublish({ normalize: true }, 1000, 0) === false);

      // The decode itself, against a real HEIC (a 16x16 red frame, 455 bytes —
      // libheif encodes and decodes it, so no network and no ffmpeg HEIF support
      // are needed). heif-convert -> JPEG -> the ordinary still pipeline.
      const heic = f('tiny.heic');
      fs.writeFileSync(heic, Buffer.from(TINY_HEIC_B64, 'base64'));
      const dst = f('tiny-out.jpg');
      const r = await media.encodeCandidate(heifPlan, heic, dst, 'test');
      const out = fs.existsSync(dst) ? fs.readFileSync(dst) : null;
      // JSON, not the csv flavour: ffprobe emits its fields in ITS order, not the
      // order they were asked for, and "mjpeg,16,16" read as width,height,codec
      // is a trap (it fooled this check the first time).
      const probe = spawnSync('ffprobe', ['-v', 'error', '-select_streams', 'v:0',
        '-show_entries', 'stream=codec_name,width,height', '-of', 'json', dst], { encoding: 'utf8' });
      let st = {};
      try { st = (JSON.parse(String(probe.stdout || '{}')).streams || [])[0] || {}; } catch {}
      check('a real HEIC decodes through heif-convert and encodes to a JPEG',
        r.ok && !!out && out.length > 0 && st.codec_name === 'mjpeg',
        JSON.stringify({ ok: r.ok, err: r.error, codec: st.codec_name }));
      check('...at its own size, never upscaled to the 2048 box',
        st.width === 16 && st.height === 16, JSON.stringify({ w: st.width, h: st.height }));
      check('a file that is not a HEIC fails the decode without crashing the worker',
        await (async () => {
          const junk = f('junk.heic');
          fs.writeFileSync(junk, Buffer.from('not a heif at all'));
          const bad = await media.encodeCandidate(heifPlan, junk, f('junk-out.jpg'), 'test');
          return bad.ok === false && /heif_decode/.test(String(bad.error || ''));
        })());
    }

    // Video: everything becomes MP4, and the containers Safari cannot demux
    // (WebM/Matroska/AVI/WMV/MPEG-TS, …) do it at ANY size — an iPhone cannot
    // play the original at all, so "smaller" is the wrong bar. MP4/M4V/
    // QuickTime are the ones Safari opens, so they keep the ordinary 8% rule.
    for (const [mime, key, normalize] of [
      ['video/mp4', 'files/a.mp4', false], ['video/quicktime', 'files/a.mov', false], ['video/x-m4v', 'files/a.m4v', false],
      ['video/webm', 'files/a.webm', true], ['video/x-matroska', 'files/a.mkv', true],
      ['application/octet-stream', 'files/a.mkv', true], ['application/octet-stream', 'files/a.avi', true],
      ['application/octet-stream', 'files/a.m2ts', true],
    ]) {
      const plan = media.planFor(mime, key);
      const ok = enc.x264 ? !!plan && plan.pipeline === 'mp4' && !!plan.normalize === normalize : plan === null;
      check(mime + ' ' + path.extname(key) + ' -> mp4' + (normalize ? ' (normalize: playable beats smaller)' : ''), ok, JSON.stringify(plan));
    }

    // Audio: MP3 or AAC/MP4, the two formats every Apple product plays.
    for (const [mime, key, want, need] of [
      ['audio/wav', 'files/a.wav', 'wav2mp3', 'mp3'], ['audio/flac', 'files/a.flac', 'wav2mp3', 'mp3'],
      ['audio/aiff', 'files/a.aiff', 'wav2mp3', 'mp3'], ['application/octet-stream', 'files/a.wma', 'wav2mp3', 'mp3'],
      ['application/octet-stream', 'files/a.amr', 'wav2mp3', 'mp3'], ['audio/mpeg', 'files/a.mp3', 'mp3', 'mp3'],
      ['audio/mp4', 'files/a.m4a', 'm4a', null],
      // Opus/Vorbis (WebM and Ogg) is the one family no Apple product could put
      // in an <audio> element before Safari 17.4 — and Ogg never at all.
      ['audio/ogg', 'files/a.ogg', 'm4a', null], ['audio/oga', 'files/a.oga', 'm4a', null],
      ['audio/opus', 'files/a.opus', 'm4a', null], ['audio/webm', 'files/a.webm', 'm4a', null],
      ['application/octet-stream', 'files/a.weba', 'm4a', null],
    ]) {
      const plan = media.planFor(mime, key);
      check(mime + ' ' + path.extname(key) + ' -> ' + want, need && !enc[need] ? plan === null : !!plan && plan.pipeline === want, JSON.stringify(plan));
    }

    // Which conversions publish at ANY size (the source is unplayable on Apple,
    // so keeping the original because the re-encode is bigger is the bug this
    // exists to prevent) and which keep the 8% rule.
    for (const [mime, key, want] of [
      ['audio/webm', 'files/a.webm', true], ['audio/ogg', 'files/a.ogg', true],
      ['audio/opus', 'files/a.opus', true], ['application/octet-stream', 'files/a.weba', true],
      ['application/octet-stream', 'files/a.wma', true], ['application/octet-stream', 'files/a.amr', true],
      ['audio/aiff', 'files/a.aiff', true], ['application/octet-stream', 'files/a.ac3', true],
      ['audio/wav', 'files/a.wav', false], ['audio/flac', 'files/a.flac', false],
      ['audio/mpeg', 'files/a.mp3', false], ['audio/mp4', 'files/a.m4a', false],
    ]) {
      const p = media.planFor(mime, key) || {};
      check(key + (want ? ' is published even when bigger (normalize)' : ' keeps the 8% rule'),
        !!p.normalize === want, JSON.stringify(p));
    }

    check('TypeScript is not mistaken for MPEG-TS',
      media.planFor('text/plain', 'files/a.ts') === null && media.planFor('application/octet-stream', 'files/a.ts') === null);
    check('a plain .webm name is read as video, not as a voice note',
      (media.planFor('application/octet-stream', 'files/a.webm') || {}).pipeline === 'mp4');

    // A resolved plan has to name a pipeline buildArgs() knows, or the encode
    // throws instead of compressing (this is how a 'still' that never got
    // resolved would show up).
    for (const p of ['jpeg', 'png', 'webp', 'gif', 'mp4', 'mp3', 'm4a', 'wav2mp3']) {
      let ok = true;
      try { media.buildArgs(p, 'in', 'out'); } catch { ok = false; }
      check('buildArgs(' + p + ') exists', ok);
    }
    // The Opus outputs are gone on purpose — they were the reason a voice note
    // was silent on an iPhone. Nothing may reintroduce one silently.
    check('no pipeline produces Opus any more',
      ['ogg', 'webaudio'].every((p) => { try { media.buildArgs(p, 'in', 'out'); return false; } catch { return true; } }));

    // The whole point, end to end on real bytes: a voice message the way Chrome
    // records it (Opus in WebM, a low bitrate) comes out as AAC in MP4 with the
    // index first, and it is PUBLISHED even though AAC is the bigger file —
    // which is the decision that used to keep the WebM.
    console.log('\n-- bytes: a WebM/Opus voice note comes out the way an iPhone plays it --');
    const voice = f('voice.webm');
    if (!gen(['-f', 'lavfi', '-i', 'sine=frequency=440:duration=2', '-c:a', 'libopus', '-b:a', '24k'], voice)) {
      console.log('  note  this ffmpeg has no libopus encoder — the voice-note case is not exercised here');
    } else {
      const vPlan = media.planFor('audio/webm', 'files/voice.webm');
      check('a Chrome voice note is planned for AAC/MP4 at any size',
        !!vPlan && vPlan.pipeline === 'm4a' && vPlan.outExt === '.m4a' && vPlan.normalize === true, JSON.stringify(vPlan));
      const vOut = f('voice-out.m4a');
      const r = await media.encodeCandidate(vPlan, voice, vOut, 'test');
      const st = fs.existsSync(vOut)
        ? JSON.parse(String(spawnSync('ffprobe', ['-v', 'error', '-show_entries', 'stream=codec_name', '-show_entries', 'format=format_name', '-of', 'json', vOut], { encoding: 'utf8' }).stdout || '{}'))
        : {};
      const stream = (st.streams || [])[0] || {};
      const inBytes = fs.statSync(voice).size, outBytes = fs.existsSync(vOut) ? fs.statSync(vOut).size : 0;
      check('...encoded as AAC-LC inside MP4 (what Safari/iOS/macOS play natively)',
        r.ok && stream.codec_name === 'aac' && /mp4|mov/.test(String((st.format || {}).format_name || '')),
        JSON.stringify({ ok: r.ok, err: r.error, codec: stream.codec_name, format: (st.format || {}).format_name }));
      const head = outBytes ? fs.readFileSync(vOut).subarray(0, 8192).toString('latin1') : '';
      check('...with the index (moov) before the audio data (+faststart — iOS will not start a progressive read without it)',
        head.includes('moov') && (!head.includes('mdat') || head.indexOf('moov') < head.indexOf('mdat')),
        JSON.stringify({ moov: head.indexOf('moov'), mdat: head.indexOf('mdat') }));
      check('...and published even though the AAC file is BIGGER than the Opus original',
        media.shouldPublish(vPlan, inBytes, outBytes) === true,
        JSON.stringify({ in: inBytes, out: outBytes, published: media.shouldPublish(vPlan, inBytes, outBytes) }));
    }

    console.log('\n-- bytes: a deferred still plan is settled by the file itself --');
    const made = [];
    const mk = (name, args) => { if (gen(args, f(name))) made.push(name); else console.log('  note  could not generate ' + name + ' (encoder missing) — skipped'); };
    mk('opaque.png', ['-f', 'lavfi', '-i', 'color=c=red:s=64x64', '-frames:v', '1']);
    mk('alpha.png', ['-f', 'lavfi', '-i', 'color=c=red@0.4:s=64x64,format=rgba', '-frames:v', '1']);
    mk('pic.bmp', ['-f', 'lavfi', '-i', 'color=c=blue:s=64x64', '-frames:v', '1']);
    mk('pic.tiff', ['-f', 'lavfi', '-i', 'color=c=green:s=64x64', '-frames:v', '1']);
    mk('anim.webp', ['-f', 'lavfi', '-i', 'testsrc=s=64x64:r=5', '-frames:v', '5', '-c:v', 'libwebp', '-loop', '0']);
    mk('anim.png', ['-f', 'lavfi', '-i', 'testsrc=s=64x64:r=5', '-frames:v', '5', '-c:v', 'apng', '-plays', '0', '-f', 'apng']);
    mk('pic.avif', ['-f', 'lavfi', '-i', 'color=c=yellow:s=64x64', '-frames:v', '1', '-c:v', 'libaom-av1', '-still-picture', '1']);
    mk('pic.jxl', ['-f', 'lavfi', '-i', 'color=c=purple:s=64x64', '-frames:v', '1', '-c:v', 'libjxl']);

    // What each one must resolve to. A PNG goes to WebP (lossy, alpha kept) —
    // or back to lossless PNG on a box without libwebp; a format with no promise
    // of its own goes to JPEG unless it has alpha; an animation is left alone,
    // because one frame is all a still encode keeps.
    const MIME = { '.png': 'image/png', '.bmp': 'image/bmp', '.tiff': 'image/tiff', '.webp': 'image/webp', '.avif': 'image/avif', '.jxl': 'image/jxl' };
    const png = enc.webp ? 'webp' : 'png';
    const expect = {
      'opaque.png': png, 'alpha.png': png, 'pic.bmp': 'jpeg', 'pic.tiff': 'jpeg',
      'pic.avif': 'jpeg', 'pic.jxl': 'jpeg', 'anim.webp': null, 'anim.png': null,
    };
    // Can this box READ BACK a fixture its own ffmpeg just wrote? Alpine's
    // current build answers "image data not found" to the WebP files its own
    // encoder produces, so `probeStill` gets no frame count and `resolvePlan`
    // keeps the file as it is — which is the documented SAFE default ("the bytes
    // said nothing"), not a regression. The animation rule can only be exercised
    // where the fixture is readable (it is on a stock ffmpeg); elsewhere the
    // case is reported out loud rather than silently dropped.
    const readable = (name) => {
      const r = spawnSync('ffprobe', ['-v', 'error', '-select_streams', 'v:0', '-count_frames',
        '-show_entries', 'stream=nb_read_frames', '-of', 'csv=p=0', f(name)], { encoding: 'utf8' });
      return /^[0-9]+/.test(String(r.stdout || '').trim());
    };
    let animChecked = 0;
    for (const name of made) {
      const src = f(name);
      const ext = path.extname(name);
      const want = expect[name];
      // Route it the way a real upload of that type would be routed, then let
      // the bytes settle the question.
      const plan = media.planFor(MIME[ext] || 'application/octet-stream', 'files/x' + ext);
      if (want === null && !readable(name)) {
        console.log('  note  ' + name + ' is not readable back on this box (its own ffmpeg wrote it) — the animation rule is not exercised here');
        continue;
      }
      if (want === null) animChecked++;
      let out = null;
      try { out = await media.resolvePlan(plan, src); } catch (e) { out = { error: String((e && e.message) || e) }; }
      const ok = out && out.error ? false : (want === null ? out === null : !!out && out.pipeline === want);
      check(name + ' -> ' + (want === null ? 'left alone' : want), ok, JSON.stringify(out) + ' from ' + JSON.stringify(plan));
      if (!out || out.error || want === null) continue;
      // ...and the resolved pipeline must actually run on those bytes.
      const dst = f('out-' + name + out.outExt);
      const r = spawnSync('ffmpeg', media.buildArgs(out.pipeline, src, dst), { stdio: 'ignore' });
      check(name + ' encodes with the ' + out.pipeline + ' pipeline', r.status === 0 && fs.existsSync(dst) && fs.statSync(dst).size > 0, 'exit=' + r.status);
      // The lossy conversion is only allowed to change the size, never to throw
      // away an alpha channel.
      if (name === 'alpha.png' && out.pipeline !== 'png') {
        const p = spawnSync('ffprobe', ['-v', 'error', '-select_streams', 'v:0', '-show_entries', 'stream=pix_fmt', '-of', 'csv=p=0', dst], { encoding: 'utf8' });
        const pix = String(p.stdout || '').trim();
        check('...and transparency survives it', /^(rgba|bgra|argb|abgr|yuva|gbrap|ya[0-9])/.test(pix), 'pix_fmt=' + pix);
      }
    }
    check('the multi-frame fixtures really were animations',
      animChecked > 0, 'generated: ' + made.join(', ') + '; animation cases exercised: ' + animChecked);

    const direct = media.planFor('image/jpeg', 'files/a.jpg');
    check('a plan that is not deferred passes through untouched', (await media.resolvePlan(direct, f('opaque.png'))) === direct);

    // The knobs are read at require time, so ask a child process what a given
    // environment produces. Concurrency 1 is the low-CPU promise (and the
    // default); the ceiling exists because every extra encode holds its own
    // decoder buffers on a box that is also serving the app.
    console.log('\n-- knobs: how many files at once, and how wide a batch --');
    const knob = (env) => {
      const r = spawnSync(process.execPath, ['-e',
        "const m=require('./media-compress');const s=m.getMediaStats();process.stdout.write(JSON.stringify({c:s.concurrency,b:s.batch,k:s.minKb}))"],
      { cwd: path.join(__dirname, '..'), env: { ...process.env, ...env }, encoding: 'utf8' });
      try { return JSON.parse(r.stdout); } catch { return null; }
    };
    const dflt = knob({ MEDIA_COMPRESS_CONCURRENCY: '', MEDIA_COMPRESS_BATCH: '', MEDIA_COMPRESS_MIN_KB: '' });
    check('defaults: 1 encode at once, 1 file per tick, no size floor', !!dflt && dflt.c === 1 && dflt.b === 1 && dflt.k === 0, JSON.stringify(dflt));
    const two = knob({ MEDIA_COMPRESS_CONCURRENCY: '2', MEDIA_COMPRESS_BATCH: '4' });
    check('a configured pair is what the worker reports', !!two && two.c === 2 && two.b === 4, JSON.stringify(two));
    const hi = knob({ MEDIA_COMPRESS_CONCURRENCY: '99', MEDIA_COMPRESS_BATCH: '99' });
    check('...and both are clamped (4 encodes, 16 per tick)', !!hi && hi.c === 4 && hi.b === 16, JSON.stringify(hi));
    const lo = knob({ MEDIA_COMPRESS_CONCURRENCY: '0', MEDIA_COMPRESS_BATCH: '-3' });
    check('...and cannot go below one', !!lo && lo.c === 1 && lo.b === 1, JSON.stringify(lo));
  } finally {
    try { fs.rmSync(tmp, { recursive: true, force: true }); } catch {}
  }

  console.log('\n' + passed + ' checks passed, ' + failures.length + ' failed');
  if (failures.length) {
    for (const x of failures) console.log('  - ' + x);
    process.exit(1);
  }
  console.log('compress coverage: OK');
}

